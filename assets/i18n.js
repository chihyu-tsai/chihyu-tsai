export function translate(text, language) {
  if (language !== 'zh-Hant') return text;
  if (Object.hasOwn(translations, text)) return translations[text];
  const count = text.match(/^(\d+) cafés · (\d+) countries · a growing journal(.*)$/);
  if (count) return `${count[1]} 間咖啡館 · ${count[2]} 個國家 · 持續累積中${translate(count[3], language)}`;
  const months = { Jan: 1, Feb: 2, Mar: 3, Apr: 4, May: 5, Jun: 6, Jul: 7, Aug: 8, Sep: 9, Oct: 10, Nov: 11, Dec: 12 };
  const date = text.match(/^([A-Z][a-z]{2}) (\d{4})$/);
  if (date && months[date[1]]) return `${date[2]} 年 ${months[date[1]]} 月`;
  return text.replace(' Map unavailable; browse all visits in the list.', ' 地圖暫時無法使用；請瀏覽清單中的咖啡足跡。')
    .replace('Cafés could not be loaded. Please try Refresh.', '無法載入咖啡館，請按「重新整理」。')
    .replace(' Previously loaded entries are kept.', ' 已保留先前載入的資料。');
}

if (typeof document !== 'undefined' && document.documentElement.dataset.design === 'v3') {
  const button = document.getElementById('language-toggle');
  const originals = new WeakMap();
  const attributeOriginals = new WeakMap();
  const attributes = ['aria-label', 'title', 'alt'];
  let language = 'en';
  try { if (localStorage.getItem('language') === 'zh-Hant') language = 'zh-Hant'; } catch { /* Storage is optional. */ }

  function excluded(node) {
    return node.parentElement?.closest('script, style, noscript, #language-toggle, .coffee-place, .coffee-popup, .maplibregl-canvas-container');
  }
  function localize() {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      const node = walker.currentNode;
      if (excluded(node) || !node.data.trim()) continue;
      let record = originals.get(node);
      if (!record || node.data !== record.last) record = { original: node.data };
      const source = record.original.trim();
      const translated = language === 'zh-Hant' && node.parentElement?.dataset.zh
        ? node.parentElement.dataset.zh : translate(source, language);
      const next = record.original.replace(source, translated);
      record.last = next;
      originals.set(node, record);
      if (node.data !== next) node.data = next;
    }
    document.querySelectorAll('[aria-label], [title], [alt]').forEach(node => {
      if (node.closest('#language-toggle, .coffee-place, .coffee-popup')) return;
      const records = attributeOriginals.get(node) || {};
      attributes.forEach(name => {
        const current = node.getAttribute(name);
        if (current === null) return;
        let record = records[name];
        if (!record || current !== record.last) record = { original: current };
        record.last = translate(record.original, language);
        records[name] = record;
        if (current !== record.last) node.setAttribute(name, record.last);
      });
      attributeOriginals.set(node, records);
    });
  }
  function setLanguage(next) {
    language = next;
    document.documentElement.lang = language;
    const action = language === 'en' ? '切換至繁體中文' : 'Switch to English';
    button.setAttribute('aria-label', action); button.title = action;
    localize();
    try { localStorage.setItem('language', language); } catch { /* Switching works without storage. */ }
    document.dispatchEvent(new CustomEvent('languagechange', { detail: language }));
  }
  button.addEventListener('click', () => setLanguage(language === 'en' ? 'zh-Hant' : 'en'));
  setLanguage(language);
  // Localize asynchronous journey labels, café status messages and theme labels.
  // Equality checks make these updates idempotent; records retain English sources.
  new MutationObserver(localize).observe(document.body, {
    childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: attributes,
  });
}
